SYSTEM_PROMPT_JUDGE = """Ты — строгий судья качества скоринга закупок. Тебе дают:
1) компетенции поставщика;
2) описание закупки;
3) оценку Fit, выставленную другой моделью, вместе с её рассуждениями.

Проверь адекватность оценки. Учитывай правило «смысл важнее слов» и опасность false-friend
(совпадающие термины с разным смыслом). Ответ — строгий JSON по схеме:
{"critics": "<замечания либо согласие>", "verdict": "accept|reject", "final_fit_score": <0..10>}
- accept — оценка адекватна, final_fit_score совпадает с оценкой модели;
- reject — оценка неадекватна (завышена/занижена/ошибочные рассуждения), укажи замечания
  в critics и назначь корректную final_fit_score.
"""


_TRUNCATED_NOTE = (
    "ВНИМАНИЕ: приведённое ниже ОПИСАНИЕ ЗАКУПКИ НЕПОЛНОЕ — оно обрезано многоточием. "
    "Опираться на него можно, но помни, что обрезанная часть может содержать информацию, "
    "важную для скоринга. Следуй правилу 7 промпта."
)

_FULL_TEXT_NOTE = (
    "ВНИМАНИЕ: ниже уже предоставлен ПОЛНЫЙ текст ТЗ (файл технического задания прочитан). "
    "Решение о чтении ТЗ уже принято: НЕ выставляй requires_tz_review=true и "
    "requires_tz_body=false. Ставь requires_tz_review=false, requires_tz_body=true. "
    "Оценивай только саму закупку по полному тексту."
)


def build_fit_messages(
    competencies: str,
    description: str,
    truncated: bool = False,
    full_text: bool = False,
) -> list[BaseMessage]:
    """Составить сообщения для fit-цепочки (система + few-shot + текущий вход).

    ``truncated=True`` — описание закупки обрезано многоточием: добавляется явное
    указание на неполноту описания (правило 7 системного промпта).
    ``full_text=True`` — уже предоставлен полный текст ТЗ (файл прочитан): модель
    не должна снова запрашивать чтение ТЗ (requires_tz_review/requires_tz_body).
    """
    messages: list[BaseMessage] = [SystemMessage(content=SYSTEM_PROMPT_FIT)]
    if truncated:
        messages.append(SystemMessage(content=_TRUNCATED_NOTE))
    if full_text:
        messages.append(SystemMessage(content=_FULL_TEXT_NOTE))
    for human, ai in FEW_SHOT:
        messages.extend(human)
        messages.extend(ai)
    messages.append(
        HumanMessage(
            content=f"КОМПЕТЕНЦИИ ПОСТАВЩИКА:\n{competencies}\n\nОПИСАНИЕ ЗАКУПКИ:\n{description}"
        )
    )
    return messages


def build_judge_messages(
    competencies: str,
    description: str,
    fit_result: str,
) -> list[BaseMessage]:
    """Составить сообщения для judge-цепочки (отдельный контекст)."""
    return [
        SystemMessage(content=SYSTEM_PROMPT_JUDGE),
        HumanMessage(
            content=(
                f"КОМПЕТЕНЦИИ ПОСТАВЩИКА:\n{competencies}\n\n"
                f"ОПИСАНИЕ ЗАКУПКИ:\n{description}\n\n"
                f"ОЦЕНКА МОДЕЛИ (JSON):\n{fit_result}\n\n"
                "Оцени адекватность этой оценки."
            )
        ),
    ]
