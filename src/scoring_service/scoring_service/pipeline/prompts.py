"""Промпты и примеры для fit- и judge-цепочек.

Подходы:
- **few-shot** — позитивные примеры «описание ↔ компетенции → эталон reasoning + fit_score»;
- **negative-example** — примеры, где термины совпадают, но смысл разный (false-friend),
  и где релевантность достигается синонимичными терминами при другой лексике.
"""

from __future__ import annotations

from langchain_core.messages import AIMessage, BaseMessage, HumanMessage, SystemMessage

SYSTEM_PROMPT_FIT = """Ты — эксперт по скорингу государственных закупок. Твоя задача — оценить,
насколько описание закупки соответствует компетенциям поставщика, и выставить Fit-оценку
от 0 до 10.

Критически важное правило:
1) **Смысл важнее слов.** Описание, семантически близкое к компетенциям, но использующее
   синонимичные термины, — это ВЫСОКАЯ оценка (8-10).
2) **Осторожно с false-friend.** Набор совпадающих терминов может НЕ означать совпадения
   смысла. Например, компетенция «консультации по выбору аппаратуры связи», а закупка —
   «консультации по выбору аппаратуры звукозаписи»: большинство слов совпадает, но смысл
   совершенно другой. Это НИЗКАЯ оценка (0-3).
3) Если закупка покрывается компетенциями лишь частично — средняя оценка (4-7).
4) Если компетенции не релевантны вовсе — низкая (0-2).
5) **Компетенция компании — автоматизация ЛЮБЫХ бизнес-процессов.** Отсутствие конкретного
   бизнес-процесса среди перечисленных ранее автоматизированных кейсов — это лишь слабый
   негативный сигнал: снижай оценку незначительно (примерно на 1-2 балла), но НЕ до минимума.
   Низкая оценка (0-3) оправдана ТОЛЬКО если суть закупки вне компетенций (поставка/монтаж
   оборудования, несмежные консультации, сопровождение конкретного чужого продукта без
   задачи автоматизации процессов).
6) **Неоднозначность продукта.** Если в описании закупки НЕ названо конкретное ПО и неясно,
   идёт ли речь о сопровождении чужого продукта или о совершенствовании/автоматизации
   процессов (это компетенция компании) — выставляй requires_tz_review=true, а fit_score
   держи в среднем диапазоне (4-6): не занижай и не завышай.
   **ВАЖНО: уточнение по полному тексту ТЗ — дорогая операция, не злоупотребляй ей.**
   requires_tz_review=true ставь ТОЛЬКО если одновременно:
   a) есть РЕАЛЬНАЯ неоднозначность продукта (ПО не названо, текст двусмыслен);
   б) закупка в остальном ПРИЕМЛЕМА для компании — скор не очевидно низкий (>=4)
      и не очевидно высокий (<=7). Если закупка уже явно вне компетенций (низкий скор)
      или уже явно релевантна (высокий скор) — requires_tz_review=false: уточнение
      по ТЗ не изменит итог и лишь потратит ресурсы.
   В остальных случаях requires_tz_review=false.

7) **Обрезанное описание (многоточие в конце).** Если описание закупки обрезано
   многоточием (неполная информация) — сначала отсеки ЯВНО нерелевантную закупку
   (низкий скор, requires_tz_review=false): обрезанная часть вряд ли изменит итог
   вне плаузибельной зоны. Если же есть сомнения, что обрезанная часть может содержать
   информацию, влияющую на скор (закупка в остальном плаузибельна) — выставляй
   requires_tz_review=true и реши, какой объём ТЗ нужен:
   - requires_tz_body=true — обрезанная часть критична, нужно читать всё тело ТЗ;
   - requires_tz_body=false — достаточно прочитать ТОЛЬКО полный заголовок ТЗ
     (расширенное описание закупки), читать всё тело ТЗ не нужно.
   Чтение только заголовка дешевле чтения всего тела ТЗ: предпочитай requires_tz_body=false,
   если неясность касается лишь формулировки/полноты описания предмета закупки.

Твой ответ — строгий JSON по схеме:
{"reasoning": {<обязательные этапы рассуждений>}, "fit_score": <0..10>,
 "requires_tz_review": <bool>, "requires_tz_body": <bool>}
Обязательные этапы рассуждений (каждый — строка):
- procurement_essence: суть закупки;
- competencies_essence: суть компетенций поставщика;
- relevant_competencies: какие компетенции релевантны закупке;
- term_overlap_mismatch_check: проверка «термины совпадают, но смысл разный»;
- synonym_semantic_bridge: релевантность через синонимы при другой лексике;
- uncovered_scope: что из закупки НЕ покрывается компетенциями (различай слабый сигнал —
  не назван процесс, но это автоматизация — и сильный — закупка вне компетенций);
- tz_review_necessity: нужно ли уточнять скор по тексту ТЗ и почему (реальная ли
  неоднозначность и оправдана ли дорогая операция; если да — нужно ли читать всё тело ТЗ
  (requires_tz_body=true) или достаточно только заголовка (requires_tz_body=false), и почему);
- fit_score_rationale: обоснование числовой оценки.
"""


def _ex(
    description: str,
    fit_score: float,
    reasoning: dict[str, str],
    negative: bool = False,
    requires_tz_review: bool = False,
    requires_tz_body: bool = True,
) -> tuple[list[BaseMessage], list[BaseMessage]]:
    """Few-shot пример: человеческий вход + эталонный ответ (AIMessage)."""
    tag = "NEGATIVE" if negative else "POSITIVE"
    human = f"[{tag}] ОПИСАНИЕ ЗАКУПКИ:\n{description}"
    reasoning_json = "{" + ", ".join(f'"{k}": "{v}"' for k, v in reasoning.items()) + "}"
    ai = (
        '{"reasoning": '
        + reasoning_json
        + f', "fit_score": {fit_score}, "requires_tz_review": '
        + ("true" if requires_tz_review else "false")
        + ', "requires_tz_body": '
        + ("true" if requires_tz_body else "false")
        + "}"
    )
    return [HumanMessage(content=human)], [AIMessage(content=ai)]


